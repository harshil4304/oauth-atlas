import { compressToEncodedURIComponent, decompressFromEncodedURIComponent } from "lz-string";
import { FACTOR_LABELS, formatRange, scoreGuide, timeHeadline } from "./rubric";
import { FACTOR_KEYS, Guide } from "./schema";
import { EVIDENCE_LABEL } from "./labels";

/** Self-contained share links: the whole guide lives in the URL fragment, so no storage is needed. */
export const encodeGuide = (g: Guide) => compressToEncodedURIComponent(JSON.stringify(g));
export function decodeGuide(s: string): Guide | null {
  try {
    const json = decompressFromEncodedURIComponent(s);
    if (!json) return null;
    const r = Guide.safeParse(JSON.parse(json));
    return r.success ? r.data : null;
  } catch {
    return null;
  }
}

const cite = (ids: string[]) => (ids.length ? " " + ids.map((i) => `[${i}]`).join("") : "");
const ev = (e: keyof typeof EVIDENCE_LABEL) => `_${EVIDENCE_LABEL[e]}_`;

export function guideToMarkdown(g: Guide): string {
  const d = scoreGuide(g);
  const L: string[] = [];
  L.push(`# ${g.name}: OAuth app setup and approval`);
  L.push("");
  L.push(`> ${g.summary}`);
  L.push("");
  L.push(`- **Difficulty:** ${d.label}`);
  L.push(`- **Time:** ${timeHeadline(g)}`);
  L.push(`- **Scenario assumed:** ${g.scenario}`);
  L.push(`- **Developer portal:** ${g.portal.url} (${g.portal.accountNeeded})`);
  L.push(`- **Composio-managed OAuth app:** ${g.composio.managed}. ${g.composio.note}`);
  L.push(`- **Last checked:** ${g.meta.lastVerified} (${g.meta.origin === "agent" ? "generated by the research agent" : "researched and checked by hand"})`);
  L.push("");
  L.push(`## Start here`);
  L.push(g.nextStep);
  L.push("");
  L.push(`## What makes it easy or hard`);
  for (const k of FACTOR_KEYS) {
    const f = g.factors[k];
    L.push(`- **${FACTOR_LABELS[k]}:** ${f.value}. ${f.detail} ${ev(f.evidence)}${cite(f.sourceIds)}`);
  }
  L.push("");
  L.push(`## Time`);
  L.push(`Your work: ${formatRange(g.time.handsOn)}. Waiting on the provider: ${g.time.approvalWait ? formatRange(g.time.approvalWait) : "none"}. ${g.time.note} ${ev(g.time.evidence)}${cite(g.time.sourceIds)}`);
  L.push("");
  if (g.prerequisites.length) {
    L.push(`## Before you start`);
    g.prerequisites.forEach((p) => L.push(`- ${p.text} ${ev(p.evidence)}${cite(p.sourceIds)}`));
    L.push("");
  }
  L.push(`## Steps`);
  g.steps.forEach((s, i) => {
    const who = s.owner === "agent" ? "Agent can do" : s.owner === "you" ? "You do" : "Agent drafts, you submit";
    L.push(`${i + 1}. **${s.title}** (${who}). ${s.detail}${s.link ? ` ${s.link}` : ""} ${ev(s.evidence)}${cite(s.sourceIds)}`);
  });
  L.push("");
  L.push(`## Review and approval`);
  L.push(`${g.review.summary} ${ev(g.review.evidence)}${cite(g.review.sourceIds)}`);
  if (g.review.triggers.length) L.push(`\nTriggered by: ${g.review.triggers.join("; ")}.`);
  if (g.review.reviewersCheck.length) L.push(`\nReviewers check: ${g.review.reviewersCheck.join("; ")}.`);
  L.push(`\nWhile you wait: ${g.review.meanwhile}`);
  L.push("");
  if (g.blockers.length) {
    L.push(`## If you get stuck`);
    g.blockers.forEach((b) => L.push(`- **${b.issue}** ${b.fix} ${ev(b.evidence)}${cite(b.sourceIds)}`));
    L.push("");
  }
  if (g.scopes.length) {
    L.push(`## Scopes`);
    g.scopes.forEach((s) => L.push(`- \`${s.name}\`: ${s.purpose} (${s.sensitivity}${s.triggersReview ? ", triggers review" : ""}) ${ev(s.evidence)}${cite(s.sourceIds)}`));
    L.push("");
  }
  if (g.nuances.length) {
    L.push(`## Good to know`);
    g.nuances.forEach((n) => L.push(`- ${n.text} ${ev(n.evidence)}${cite(n.sourceIds)}`));
    L.push("");
  }
  if (g.uncertainties.length) {
    L.push(`## Not confirmed`);
    g.uncertainties.forEach((u) => L.push(`- ${u}`));
    L.push("");
  }
  L.push(`## Sources`);
  g.sources.forEach((s) => L.push(`- [${s.id}] ${s.title} (${s.kind}, checked ${s.checkedAt}): ${s.url}`));
  return L.join("\n") + "\n";
}
