import type { Guide } from "@/lib/schema";
import { FACTOR_KEYS } from "@/lib/schema";
import { FACTOR_LABELS, WEIGHTS, scoreGuide, timeHeadline } from "@/lib/rubric";
import { ComposioTag, DifficultyBadge, EVIDENCE, Evidence } from "./Badges";
import { Timeline, TimelineLegend } from "./Timeline";
import { StepsChecklist } from "./StepsChecklist";
import { ShareBar } from "./ShareBar";
import { LiveChecks } from "./LiveChecks";

const VALUE_TEXT = { yes: "Required", no: "Not required", depends: "Sometimes", unknown: "Unknown" } as const;

function Section({ id, title, children, note }: { id: string; title: string; children: React.ReactNode; note?: string }) {
  return (
    <section id={id} className="scroll-mt-6 border-t border-line pt-6">
      <h2 className="text-xl font-bold">{title}</h2>
      {note && <p className="mt-1 text-sm text-ink-3">{note}</p>}
      <div className="mt-4">{children}</div>
    </section>
  );
}

export function GuideView({ guide: g, persisted = true }: { guide: Guide; persisted?: boolean }) {
  const d = scoreGuide(g);
  const src = g.sources;
  const agentSteps = g.steps.filter((s) => s.owner === "agent").length;
  const togetherSteps = g.steps.filter((s) => s.owner === "together").length;
  const youSteps = g.steps.length - agentSteps - togetherSteps;
  const testedCount = g.probes.filter((p) => p.result === "pass").length;

  return (
    <article className="pt-8">
      <header className="max-w-3xl">
        <p className="text-sm text-ink-3">
          {g.category} ·{" "}
          {g.meta.origin === "agent" ? "Generated by the research agent" : "Researched and checked by hand"}, last checked {g.meta.lastVerified}
        </p>
        <h1 className="mt-2 text-4xl font-extrabold sm:text-5xl">{g.name}</h1>
        <p className="mt-3 text-lg text-ink-2">{g.summary}</p>
        <p className="mt-2 text-sm text-ink-3">
          Rated for this use case: <span className="text-ink-2">{g.scenario}</span>
        </p>
      </header>

      <div className="mt-8 rounded-xl border border-line bg-surface p-5 sm:p-6">
        <div className="flex flex-wrap items-center gap-x-5 gap-y-2">
          <DifficultyBadge d={d} large />
          <span className="font-display text-lg font-bold">{timeHeadline(g)}</span>
          <span className="sm:ml-auto">
            <ComposioTag managed={g.composio.managed} />
          </span>
        </div>
        <div className="mt-6">
          <Timeline guide={g} />
          <TimelineLegend guide={g} />
        </div>
        <p className="mt-3 text-sm text-ink-3">
          {g.time.note} <Evidence level={g.time.evidence} sourceIds={g.time.sourceIds} sources={src} />
        </p>
      </div>

      <div className="mt-6 rounded-xl bg-work-soft p-5">
        <h2 className="font-display text-base font-bold text-work">Start here</h2>
        <p className="mt-1 text-ink">{g.nextStep}</p>
        <p className="mt-3 text-sm text-ink-2">
          {g.steps.length} steps: an agent can do {agentSteps} on its own, draft {togetherSteps} for you to submit, and {youSteps} need you.
        </p>
      </div>

      <div className="mt-10 grid grid-cols-[minmax(0,1fr)] gap-10 lg:grid-cols-[minmax(0,1fr)_320px]">
        <div className="space-y-10">
          <Section id="steps" title="Steps" note="Tick steps off as you go; progress is saved in this browser.">
            <StepsChecklist slug={g.slug} steps={g.steps} sources={src} />
          </Section>

          {g.prerequisites.length > 0 && (
            <Section id="before" title="Have these ready">
              <ul className="space-y-3">
                {g.prerequisites.map((p, i) => (
                  <li key={i} className="max-w-[70ch]">
                    {p.text} <Evidence level={p.evidence} sourceIds={p.sourceIds} sources={src} />
                  </li>
                ))}
              </ul>
            </Section>
          )}

          <Section id="review" title="Review and approval">
            <p className="max-w-[70ch]">
              {g.review.summary} <Evidence level={g.review.evidence} sourceIds={g.review.sourceIds} sources={src} />
            </p>
            <dl className="mt-4 grid gap-4 sm:grid-cols-2">
              {g.review.triggers.length > 0 && (
                <div>
                  <dt className="text-sm font-semibold text-ink-2">What triggers it</dt>
                  <dd>
                    <ul className="mt-1 list-disc space-y-1 pl-5">
                      {g.review.triggers.map((t, i) => (
                        <li key={i}>{t}</li>
                      ))}
                    </ul>
                  </dd>
                </div>
              )}
              {g.review.reviewersCheck.length > 0 && (
                <div>
                  <dt className="text-sm font-semibold text-ink-2">What reviewers look at</dt>
                  <dd>
                    <ul className="mt-1 list-disc space-y-1 pl-5">
                      {g.review.reviewersCheck.map((t, i) => (
                        <li key={i}>{t}</li>
                      ))}
                    </ul>
                  </dd>
                </div>
              )}
            </dl>
            <p className="mt-4 max-w-[70ch] text-ink-2">
              <span className="font-semibold text-ink">While you wait: </span>
              {g.review.meanwhile}
            </p>
          </Section>

          {g.blockers.length > 0 && (
            <Section id="blockers" title="If you get stuck">
              <ul className="divide-y divide-line">
                {g.blockers.map((b, i) => (
                  <li key={i} className="py-3 first:pt-0">
                    <p className="font-semibold">{b.issue}</p>
                    <p className="mt-1 max-w-[70ch] text-ink-2">
                      {b.fix} <Evidence level={b.evidence} sourceIds={b.sourceIds} sources={src} />
                    </p>
                  </li>
                ))}
              </ul>
            </Section>
          )}

          {g.scopes.length > 0 && (
            <Section id="scopes" title="Scopes an agent typically needs">
              <div className="overflow-x-auto">
                <table className="w-full min-w-[520px] text-left text-sm">
                  <thead className="text-ink-3">
                    <tr className="border-b border-line">
                      <th className="py-2 pr-4 font-normal">Scope</th>
                      <th className="py-2 pr-4 font-normal">Lets the agent</th>
                      <th className="py-2 pr-4 font-normal">Sensitivity</th>
                      <th className="py-2 font-normal">Evidence</th>
                    </tr>
                  </thead>
                  <tbody>
                    {g.scopes.map((s, i) => (
                      <tr key={i} className="border-b border-line align-top">
                        <td className="py-2 pr-4">
                          <code className="break-all">{s.name}</code>
                        </td>
                        <td className="py-2 pr-4">{s.purpose}</td>
                        <td className={`py-2 pr-4 ${s.sensitivity === "restricted" ? "text-hard" : s.sensitivity === "sensitive" ? "text-wait" : ""}`}>
                          {s.sensitivity}
                          {s.triggersReview ? ", triggers review" : ""}
                        </td>
                        <td className="py-2">
                          <Evidence level={s.evidence} sourceIds={s.sourceIds} sources={src} />
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </Section>
          )}

          {g.nuances.length > 0 && (
            <Section id="nuances" title="Good to know">
              <ul className="space-y-3">
                {g.nuances.map((n, i) => (
                  <li key={i} className="max-w-[70ch]">
                    {n.text} <Evidence level={n.evidence} sourceIds={n.sourceIds} sources={src} />
                  </li>
                ))}
              </ul>
            </Section>
          )}

          <Section id="unconfirmed" title="What we could not confirm">
            {g.uncertainties.length ? (
              <ul className="list-disc space-y-2 pl-5">
                {g.uncertainties.map((u, i) => (
                  <li key={i} className="max-w-[70ch]">
                    {u}
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-ink-2">Nothing flagged. Claims marked Unconfirmed above still deserve a check.</p>
            )}
            {g.meta.corrections.length > 0 && (
              <>
                <h3 className="mt-6 text-base font-bold">What research changed</h3>
                <ul className="mt-2 list-disc space-y-2 pl-5 text-ink-2">
                  {g.meta.corrections.map((c, i) => (
                    <li key={i} className="max-w-[70ch]">
                      {c}
                    </li>
                  ))}
                </ul>
              </>
            )}
          </Section>

          <Section id="sources" title="Sources">
            <ol className="space-y-2 text-sm">
              {g.sources.map((s) => (
                <li key={s.id} id={`src-${s.id}`} className="scroll-mt-6">
                  <span className="mono text-ink-3">[{s.id}]</span>{" "}
                  <a href={s.url} target="_blank" rel="noreferrer" className="underline">
                    {s.title}
                  </a>{" "}
                  <span className="text-ink-3">
                    {s.kind === "official" ? "provider page" : "community"}, read {s.checkedAt}
                  </span>
                </li>
              ))}
            </ol>
          </Section>
        </div>

        <aside className="space-y-8 lg:sticky lg:top-6 lg:self-start">
          <div>
            <h2 className="font-display text-base font-bold">Why it&apos;s rated {d.label}</h2>
            <p className="mt-1 text-sm text-ink-3">
              Score {d.min === d.max ? d.min : `${d.min}–${d.max}`} from fixed weights. Ranges come from Sometimes or Unknown answers.{" "}
              <a href="/method" className="underline">
                How we rate
              </a>
            </p>
            <ul className="mt-3 space-y-3">
              {FACTOR_KEYS.map((k) => {
                const f = g.factors[k];
                return (
                  <li key={k} className="text-sm">
                    <details>
                      <summary className="flex cursor-pointer list-none items-baseline gap-2">
                        <span
                          className={`w-24 shrink-0 font-semibold ${f.value === "yes" ? "text-hard" : f.value === "no" ? "text-work" : "text-[color-mix(in_srgb,var(--wait)_75%,var(--ink))]"}`}
                        >
                          {VALUE_TEXT[f.value]}
                        </span>
                        <span>
                          {FACTOR_LABELS[k]} <span className="text-ink-3">({WEIGHTS[k]} pts)</span>
                        </span>
                      </summary>
                      <p className="mt-1 pl-26 text-ink-2">
                        {f.detail} <Evidence level={f.evidence} sourceIds={f.sourceIds} sources={src} />
                      </p>
                    </details>
                  </li>
                );
              })}
            </ul>
            {d.drivers.some((x) => x.key === "effort") && <p className="mt-2 text-sm text-ink-3">+1 because setup itself takes a day or more.</p>}
          </div>

          <ShareBar guide={g} persisted={persisted} />

          <LiveChecks slug={g.slug} initial={g.probes} canRerun={persisted} />

          <div>
            <h2 className="font-display text-base font-bold">How sure are we?</h2>
            <ul className="mt-2 space-y-1 text-sm">
              {(Object.keys(EVIDENCE) as (keyof typeof EVIDENCE)[]).map((k) => (
                <li key={k}>
                  <span className={EVIDENCE[k].cls}>
                    <span aria-hidden>{EVIDENCE[k].mark}</span> {EVIDENCE[k].label}
                  </span>
                  <span className="text-ink-3">: {EVIDENCE[k].help}</span>
                </li>
              ))}
            </ul>
            {g.meta.checker && (
              <p className="mt-3 text-sm text-ink-2">
                Fact-check pass re-read the cited pages for {g.meta.checker.checked} key claims: {g.meta.checker.supported} confirmed, {g.meta.checker.downgraded}{" "}
                downgraded to Unconfirmed.
              </p>
            )}
            {testedCount > 0 && <p className="mt-2 text-sm text-ink-2">{testedCount} live checks passed when this guide was generated.</p>}
          </div>
        </aside>
      </div>
    </article>
  );
}
